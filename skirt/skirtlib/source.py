# ------------------------------------------------------------------ git 形式

def _git_candidates(src: dict) -> list[str]:
    """git 形式里的仓库地址，主仓库在前，然后依次是镜像。"""
    out = [src["git"].rstrip("/")]
    for m in src.get("mirrors", []):
        m = m.rstrip("/")
        if m not in out:
            out.append(m)
    return out


def _repo_name(git_url: str) -> str:
    """从仓库地址里取个短名字，用来给缓存文件命名。"""
    return git_url.rstrip("/").rsplit("/", 1)[-1].removesuffix(".git")


# ── 源码【不缓存】──────────────────────────────────────────────────────────
#
# 2026-10-15 的决定：完全移除那份缓存。
#
# 【原来是什么样】
#
# 下载过的源码留在 var/cache/ 里，下次构建如果文件名和声明的 sha256 都对得上，
# 就直接用它，不再下载。省的是网络时间。
#
# 【为什么去掉】
#
# 它只对【同一台机器上的重复构建】有意义，而我们现在没有任何在本地构建的
# 计划。而它带来的问题是真的：
#
#   · 缓存的有效性靠的是「URL 最后一段 + sha256」这两个东西碰巧对得上，
#     不是由配方内容算出来的。改了配方里的源，得靠人记得清缓存 ——
#     而这一条已经写进过文档，说明它真的咬过人。
#
#   · CI 那两条线上它的处境不一样，而都不好：
#       release.yml    根本不缓存它 → 每次都是空的 → 它一点用没有
#       bootstrap.yml  缓存了它，而 restore-keys 会退到上一轮的缓存
#                      → 改了配方之后，可能用到上一轮的旧源码
#     也就是说：它在该有用的地方（本地）用不上，在该干净的地方（CI）
#     反而可能带来旧东西。
#
# 【现在是什么样】
#
# 每次构建都下载一次，下到 var/work/download/ 下，而那个目录在每次 fetch 时
# 先清空。**没有"上一次"，所以不可能用到旧的。**
#
# 校验没变：sha256 仍然逐个源验，换源仍然会打印出来。sha256 才是信任边界，
# 而它和缓存无关。


def _scratch(name: str) -> Path:
    """本次构建的下载落点。

    每次调用先清空整个目录 —— 上一个包的下载、上一次的残留，一起没。
    """
    d = BUILD_DIR / "download"
    rmtree_force(d)
    d.mkdir(parents=True)
    return d / name


def fetch_git(spec: dict, src: dict) -> Path:
    """从 git 仓库取某个 commit，做成 tar。

    【为什么用 git 而不是托管商的归档链接】

    配方该说的是「哪个仓库的哪个 commit」，不是「去哪台机器的哪个路径拿」。
    链接格式是托管商定的，而且各不相同：GitHub 是 codeload，Gitea/Forgejo
    是 /archive/<sha>.tar.gz，GitLab 又是另一种。写配方的人不该记这些。

    更重要的是校验：**git 自己校验 commit**。commit hash 就是那棵树的内容
    哈希，比 sha256 更强——sha256 钉的是一份【字节】，而不同托管生成的归档
    字节可以不一样，于是单个 sha256 根本盖不住多个镜像。

    所以 git 形式【不需要 sha256】，也就天然支持任意数量的镜像：主仓库不通
    就换下一个，内容对不对由 git 保证。

    【实现】clone 到临时目录，再用 `git archive` 打一份 tar.gz。
    git archive 的输出是确定性的，配合 SOURCE_DATE_EPOCH 满足 0005。
    """
    pkg = spec["package"]
    commit = src.get("commit")
    if not commit:
        die(f"{pkg['name']}: [[source]] 用了 git 但没写 commit")

    repos = _git_candidates(src)
    dest = _scratch(f"{_repo_name(repos[0])}-{commit[:12]}.tar")

    import subprocess
    import tempfile
    errors: list[str] = []

    for i, repo in enumerate(repos):
        log("取源码" if i == 0 else "换镜像", f"{repo} @ {commit[:12]}")
        with tempfile.TemporaryDirectory() as td:
            work = Path(td) / "repo"
            try:
                subprocess.run(["git", "init", "-q", str(work)], check=True,
                               capture_output=True)
                subprocess.run(["git", "-C", str(work), "remote", "add",
                                "origin", repo], check=True, capture_output=True)
                # 先试只取这一个 commit（快）；服务器不允许按 sha 取时，
                # 退成完整 fetch。
                r = subprocess.run(
                    ["git", "-C", str(work), "fetch", "-q", "--depth", "1",
                     "origin", commit], capture_output=True, text=True)
                if r.returncode != 0:
                    subprocess.run(["git", "-C", str(work), "fetch", "-q",
                                    "origin"], check=True, capture_output=True)
                subprocess.run(["git", "-C", str(work), "checkout", "-q",
                                commit], check=True, capture_output=True)

                # ★ 删掉 .gitattributes —— 上游可以用它把文件从 git archive 里剔除。
                #
                #   实测撞到 strace：
                #
                #       .gitattributes:
                #           /* export-ignore
                #           /README-github_gitlab-autogenerated-archives.txt -export-ignore
                #
                #   `/* export-ignore` 是「所有顶层文件都别进归档」。于是 git archive
                #   出来的 tar 里【只剩第二行那条反向规则保住的一个说明文件】：
                #
                #       驱动的做法:      10,240 字节      顶层文件 0 个
                #       删掉再归档:  14,192,640 字节      顶层文件 2180 个
                #
                #   而症状离成因极远 —— 构建在 $SRCDIR 里跑 ./bootstrap，报的是：
                #
                #       ./bootstrap: No such file or directory
                #
                #   而 configure.ac / Makefile.am 也都不在。看起来像「驱动没铺源码」，
                #   实际是源码铺了、只是归档时被上游的规则剔掉了。
                #
                #   上游的意图是清楚的（那第二行 -export-ignore 反向保留说明文件，
                #   就是要人看到「别用自动归档，去 git clone」）。但构建要的不是
                #   「他们想让归档长什么样」，是【那棵树】。
                #
                #   两步：
                #     ① 删掉工作树里的 .gitattributes，以及 .git/info/attributes
                #        （后者也能带 export-ignore，而且不在版本控制里，容易漏）
                #     ② git archive 加 --worktree-attributes
                #        （让它以工作树那份为准 —— 而那份已经没了）
                (work / ".gitattributes").unlink(missing_ok=True)
                (work / ".git" / "info" / "attributes").unlink(missing_ok=True)
                # 用纯 tar 不用 tgz：git archive 的 tar 输出是确定性的，
                # tgz 还要看 gzip 的头部时间。tarfile.open 按内容识别压缩，
                # 所以解压那边不用改。
                with open(dest, "wb") as f:
                    subprocess.run(
                        ["git", "-C", str(work), "archive", "--worktree-attributes", "--format=tar",
                         f"--prefix={_repo_name(repo)}-{commit[:12]}/", commit],
                        check=True, stdout=f)
            except subprocess.CalledProcessError as exc:
                detail = (exc.stderr or b"").decode("utf-8", "ignore")[:200]
                errors.append(f"{repo}\n           {detail.strip()}")
                dest.unlink(missing_ok=True)
                continue
        log("校验", "git 已按 commit 校验内容")
        return dest

    dest.unlink(missing_ok=True)
    die(f"{pkg['name']}: 所有 git 源都取不到 {commit[:12]}\n         "
        + "\n         ".join(errors))


# -------------------------------------------------------------- 下载校验

def _download(url: str, dest: Path) -> None:
    """下载一个 URL 到 dest。失败抛异常。

    ★ 为什么会有 curl 这条回退 ─────────────────────────────────────────────

    macOS 上 Python 的 SSL 栈对 hg.mozilla.org 会【握手成功、然后在读数据时
    断掉】：

        URLError: <urlopen error [SSL: UNEXPECTED_EOF_WHILE_READING]
                   EOF occurred in violation of protocol>

    而同一个 URL、同一台机器，curl 一次就下来了——sha256 和 CI 上的一致。
    握手本身是成功的（TLSv1.3 / TLS_AES_256_GCM_SHA384），断在数据阶段，
    像是按 TLS 客户端指纹做了什么。

    Linux 上（CI 的 runner、容器里）Python 一切正常。所以这是 macOS 这台
    【开发机】的问题，不是配方的问题。

    ★ 回退不降低任何安全性：调用方仍然按 sha256 校验，那才是信任边界。
      这里决定的只是"用哪个客户端去取字节"。
    """
    try:
        urllib.request.urlretrieve(url, dest)
        return
    except Exception as first:                      # noqa: BLE001
        curl = shutil.which("curl")
        if not curl:
            raise

        dest.unlink(missing_ok=True)
        proc = subprocess.run(
            [curl, "-fsSL", "--max-time", "300", "-o", str(dest), url],
            capture_output=True,
            text=True,
        )
        if proc.returncode != 0:
            dest.unlink(missing_ok=True)
            raise RuntimeError(
                f"urllib 失败（{type(first).__name__}: {first}）；"
                f"curl 也失败（退出码 {proc.returncode}: {proc.stderr.strip()[:200]}）"
            ) from first


def _candidates(spec: dict, src: dict, arch: str = "") -> list[str]:
    """按顺序返回该试的 URL：`url` 优先，然后是 `urls` 里的备选。

    为什么要多个源：上游会宕、会被墙、会慢。实测 `ftp.gnu.org` 在这台机器上
    就时通时不通——同一个地址，构建 glibc 时是通的，加 patch 配方时就不通了。

    **sha256 才是身份，URL 只是提示。** 所以换源不降低信任：不管从哪拿到，
    内容对不上就拒绝。
    """
    out: list[str] = []
    if src.get("url"):
        out.append(expand(spec, src["url"], arch))
    for u in src.get("urls", []):
        e = expand(spec, u, arch)
        if e not in out:
            out.append(e)

    if not out:
        die(f"{spec['package']['name']}: [[source]] 缺少 url")
    return out


def fetch(spec: dict, arch: str = "") -> Path:
    pkg = spec["package"]
    sources = spec.get("source") or []
    if not sources:
        die(f"{pkg['name']}: 配方没有声明 source")

    src = sources[0]

    # git 形式：说清仓库和 commit，取法由驱动决定。
    if src.get("git"):
        return fetch_git(spec, src)

    urls = _candidates(spec, src, arch)

    want = str(src.get("sha256", "")).strip().lower()
    if len(want) != 64:
        die(f"{pkg['name']}: 源码没有声明有效的 sha256"
            f"（不接受未校验的源码，当前值: {want!r}）")

    # 文件名取第一个 URL 的。镜像站对同一个文件用的名字是一样的——GNU 的
    # 镜像就是这样，所以这不成问题。
    dest = _scratch(urls[0].rsplit("/", 1)[-1])
    tmp = dest.with_name(dest.name + ".part")
    errors: list[str] = []
    for i, url in enumerate(urls):
        log("下载" if i == 0 else "换源", url)
        try:
            _download(url, tmp)
        except Exception as exc:                    # noqa: BLE001
            errors.append(f"{url}\n           {type(exc).__name__}: {exc}")
            tmp.unlink(missing_ok=True)
            continue

        # ★ 校验放在【循环里】，每个源各自验一遍。
        #
        # 原来是在循环之后统一验，失败就 die。注释里给的理由是
        # 「悄悄换源会把镜像被投毒变成构建成功」——**那个担心是错的**：
        # **sha256 才是安全边界，不是"哪个源"**。被投毒的源产不出正确的
        # 字节，它在这一步照样过不去。换源不降低任何安全性。
        #
        # 而代价是实打实的：实测 CI 的 x86_64 上，zlib 从 zlib.net 下到的
        # 字节是坏的（本地同一个 URL 下来是好的），于是整个引导停在
        # [11/42]，白跑一小时。
        #
        # **换源重试，但要说出来**——不是"悄悄换"。下面每次失败都会打印。
        got = sha256_of(tmp)
        if got != want:
            log("校验失败", f"{url}\n"
                            f"           期望 {want[:16]}…  实际 {got[:16]}…")
            errors.append(f"{url}\n           sha256 不匹配"
                          f"（期望 {want}，实际 {got}）")
            tmp.unlink(missing_ok=True)
            continue

        tmp.rename(dest)
        log("校验", "sha256 匹配")
        return dest

    die(f"{pkg['name']}: 所有源都取不到或校验不通过\n       "
        + "\n       ".join(errors))


def _member_names(archive: Path) -> list[str]:
    """读归档里的成员名 —— tar 和 zip 都行。

    ★ 为什么需要 zip：Python 的 wheel 就是一个 zip。

    meson 只以 wheel 的形式发布（PyPI 上的 meson-1.12.1-py3-none-any.whl），
    而 tarfile 完全不认它——实测它把 gz/bz2/xz/zst/tar 五种方法都试了一遍，
    最后报 "file could not be opened successfully"。所以只支持 tar 的话，
    任何 Python 包都建不了。

    判断方式用【内容】而不是扩展名：`.whl` 是约定，不是格式。zipfile.is_zipfile
    读的是魔数。
    """
    if zipfile.is_zipfile(archive):
        with zipfile.ZipFile(archive) as zf:
            return zf.namelist()
    with tarfile.open(archive) as tf:
        return tf.getnames()


def srcrel_of(archive: Path) -> str:
    """源码根目录的相对名（'.' 表示解压出来就是根）。

    ★ **只读 tar 里的名字，不落盘。**

    这是踩出来的：原先直接在宿主上解压，而 macOS 的 APFS 默认大小写不敏感。
    实测内核源码里有 13 组只差大小写的文件——

        include/uapi/linux/netfilter/xt_MARK.h  /  xt_mark.h
        include/uapi/linux/netfilter/xt_DSCP.h  /  xt_dscp.h
        net/netfilter/xt_TCPMSS.c               /  xt_tcpmss.c
        …（共 13 组）

    在宿主上解压之后，每一组都只剩一个，13 组变 0 组。而它们不是重复文件：
    `MARK` 是给包打标记、`mark` 是匹配那个标记——是大写那个把小写那个覆盖了，
    于是 xt_mark.c 找不到它 include 的 xt_mark.h，构建在 47 分钟后失败。

    读成员名不会有这个问题：名字只是字符串，物化成文件树才有文件系统语义。

    解压本身挪进容器（见 build.py 里 wrapper 的注释），那里是 Linux 原生
    文件系统，大小写敏感。
    """
    names = _member_names(archive)
    tops = {n.split("/")[0] for n in names if n and not n.startswith("/")}
    if len(tops) == 1:
        top = tops.pop()
        # 成员名里有 "top/..." 才说明它是个目录（而不是单个文件）
        if any(n.startswith(top + "/") for n in names):
            return top
    return "."


def extract(archive: Path, into: Path) -> str:
    """解压到 into，返回源码根目录相对名（'.' 表示就是 into 本身）。

    ⚠️ **不要在宿主上调用它**——理由见 srcrel_of 的注释。
    留着是为了给测试和不介意大小写的场合用；真正的构建路径走
    srcrel_of + 容器内解压。
    """
    rmtree_force(into)
    into.mkdir(parents=True)
    log("解压", archive.name)
    with tarfile.open(archive) as tf:
        try:
            tf.extractall(into, filter="data")
        except TypeError:      # Python < 3.12
            tf.extractall(into)
    entries = list(into.iterdir())
    if len(entries) == 1 and entries[0].is_dir():
        return entries[0].name
    return "."


