# 命令提示符。
#
# 【为什么需要它】
#
# 不设 PS1 的话 bash 用它自己的出厂默认，于是 SSH 上去看到：
#
#     -bash-5.3#
#     ↑    ↑   ↑
#     │    │   └ 版本
#     │    └───── shell 名
#     └────────── login shell 的前导减号
#
# 那句话不算错，但它是**没人设过**的痕迹：三个位置全是 bash 在报自己，
# 跟你「是谁、在哪、在哪台机器上」全都无关。
#
# 【格式抄的是 Fedora】
#
#     [\u@\h \W]\$
#      └┬─┘└┬┘└┬┘ └┬┘
#       │   │  │   └── \$   root 是 #，普通用户是 $
#       │   │  └────── \W   当前目录【只留最后一段】（家目录缩写成 ~）
#       │   └───────── \h   主机名（短）
#       └───────────── \u   用户名
#
#     [root@YojigenOS ~]#
#
# ★ 用 \W 而不是 \w：后者是全路径，深几层之后提示符会吃掉半个屏幕：
#
#       \w  →  /usr/share/man/man8        （Debian 那种）
#       \W  →  man8                       （Fedora 那种）
#
#   方括号是【视觉定界】——一眼看出提示符从哪开始、命令从哪开始。
#
# 【下面这个条件比格式更值得抄，但 Fedora 那版只兜了一半】
#
# 别的发行版多是【直接赋值】，于是用户在 ~/.bashrc 里设的会被 /etc 这份踩掉。
# Fedora 的写法是"只在 PS1 还是那个出厂默认时才换"——**用户设过的就不动**。
#
# 但实测 bash 的默认值取决于是否交互式：
#
#     交互式（真 pty）   PS1=[\s-\v\$ ]     带尾空格
#     非交互式           PS1=[]              长度 0
#
# 两种都是"用户还没表达过意见"，所以两种都该换。
#
# ★ 这里【不能】用 case：case 的 pattern 里 "\s" 会被当成转义（变成 s）。
#   [ 的两边是字符串比较，单引号里的是字面量。
if [ -z "${PS1-}" ] || [ "$PS1" = '\s-\v\$ ' ]; then
    PS1='[\u@\h \W]\$ '
fi

# ★ 不用 export：PS1 是 shell 自己的变量，不是环境变量。导出它没意义
#   （子 shell 不会因此换提示符），还会让子进程带着一份没人读的副本。
#   Debian / Fedora 都不导，我们也不导。
